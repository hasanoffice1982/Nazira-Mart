def variant(product, color, size=None):
    return product.find_variant(Color.objects.get(name=color).pk, Size.objects.get(name=size).pk if size else None)


def add(client, product, **data):
    return client.post(reverse("cart:add", args=[product.pk]), data)


# ---- model rules -------------------------------------------------------------------
def test_product_helpers(shoes, tote):
    assert shoes.has_variants and len(shoes.colors) == 2 and [s.name for s in shoes.sizes] == ["40", "41", "42", "43"]
    assert shoes.total_stock == 48
    assert tote.price_varies and tote.from_price == tote.price  # one variant overrides the price upwards


def test_variant_sku_autogenerated_and_label(shoes):
    v = variant(shoes, "Cloud", "42")
    assert v.sku == f"{shoes.sku}-CLOUD-42" and v.label == "Cloud / 42"


def test_variant_needs_color_or_size(shoes):
    with pytest.raises(IntegrityError), transaction.atomic():
        ProductVariant.objects.create(product=shoes, sku="X-EMPTY")


def test_duplicate_combinations_rejected(shoes, tote):
    with pytest.raises(IntegrityError), transaction.atomic():
        ProductVariant.objects.create(product=shoes, color=Color.objects.get(name="Cloud"), size=Size.objects.get(name="42"), sku="DUP-1")
    with pytest.raises(IntegrityError), transaction.atomic():  # colour-only duplicates (NULL size) are blocked too
        ProductVariant.objects.create(product=tote, color=Color.objects.get(name="Sand"), sku="DUP-2")


def test_inactive_variants_are_ignored(shoes):
    ProductVariant.objects.filter(product=shoes).update(is_active=False)
    shoes = Product.objects.get(pk=shoes.pk)
    assert not shoes.has_variants and shoes.total_stock == shoes.stock


