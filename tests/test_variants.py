def checkout(client, user):
    client.force_login(user)
    return client.post(reverse("orders:checkout"), DELIVERY)


def test_order_snapshots_variant_and_decrements_variant_stock(client, shoes, user):
    v = variant(shoes, "Cloud", "42")
    stock, product_stock = v.stock, shoes.stock
    client.force_login(user)
    add(client, shoes, color=v.color_id, size=v.size_id); add(client, shoes, color=v.color_id, size=v.size_id)
    client.post(reverse("orders:checkout"), DELIVERY)
    item = Order.objects.get().items.get()
    assert item.variant_label == "Cloud / 42" and item.sku == v.sku and item.quantity == 2
    v.refresh_from_db(); shoes.refresh_from_db()
    assert v.stock == stock - 2 and shoes.stock == product_stock  # product-level stock untouched


def test_order_uses_variant_price(client, tote, user):
    sage = variant(tote, "Sage")
    client.force_login(user)
    add(client, tote, color=sage.color_id)
    client.post(reverse("orders:checkout"), DELIVERY)
    assert Order.objects.get().items.get().unit_price == 1390


def test_cancel_restores_variant_stock(client, shoes, user):
    v = variant(shoes, "Mint", "41")
    stock = v.stock
    client.force_login(user)
    add(client, shoes, color=v.color_id, size=v.size_id)
    client.post(reverse("orders:checkout"), DELIVERY)
    client.post(reverse("orders:cancel", args=[Order.objects.get().number]))
    v.refresh_from_db()
    assert v.stock == stock


