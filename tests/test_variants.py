def test_cart_respects_per_variant_stock(client, shoes):
    v = variant(shoes, "Cloud", "40")
    ProductVariant.objects.filter(pk=v.pk).update(stock=2)
    for _ in range(4):
        add(client, shoes, color=v.color_id, size=v.size_id)
    assert client.get("/").context["cart_count"] == 2


def test_variant_price_used_in_cart(client, tote):
    sage = variant(tote, "Sage")
    add(client, tote, color=sage.color_id)
    assert client.get("/").context["cart_subtotal"] == 1390


def test_qty_and_remove_target_the_right_variant(client, shoes):
    a, b = variant(shoes, "Cloud", "40"), variant(shoes, "Cloud", "41")
    for v in (a, b):
        add(client, shoes, color=v.color_id, size=v.size_id)
    client.post(reverse("cart:qty", args=[shoes.pk]), {"delta": "1", "variant": a.pk})
    lines = {l.variant.pk: l.quantity for l in client.get("/").context["cart_lines"]}
    assert lines == {a.pk: 2, b.pk: 1}
    client.post(reverse("cart:remove", args=[shoes.pk]), {"variant": a.pk})
    assert [l.variant.pk for l in client.get("/").context["cart_lines"]] == [b.pk]


