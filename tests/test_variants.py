def test_add_specific_variant_and_separate_lines(client, shoes):
    cloud, mint = Color.objects.get(name="Cloud"), Color.objects.get(name="Mint")
    s41, s42 = Size.objects.get(name="41"), Size.objects.get(name="42")
    add(client, shoes, color=cloud.pk, size=s41.pk)
    add(client, shoes, color=cloud.pk, size=s41.pk)
    add(client, shoes, color=mint.pk, size=s42.pk)
    resp = client.get("/")
    assert b"Cloud / 41" in resp.content and b"Mint / 42" in resp.content
    assert resp.context["cart_count"] == 3 and len(resp.context["cart_lines"]) == 2


def test_unavailable_combination_rejected(client, shoes):
    ProductVariant.objects.filter(product=shoes, size__name="42", color__name="Mint").update(is_active=False)
