#!/usr/bin/env bash
# Make Nginx see the REAL visitor IP when the site is behind Cloudflare.
#
# Without this, every request appears to come from a Cloudflare address, so the app's rate limits and login lockouts
# (django-axes / django-ratelimit) would be shared by all visitors. With it, Nginx replaces $remote_addr with the
# CF-Connecting-IP header, but ONLY for requests that really come from Cloudflare's published ranges, so the header
# can't be spoofed by someone reaching the server directly.
#
# Usage (root):   deploy/cloudflare-realip.sh          generate the config and reload Nginx
# Environment:    OUT=<file>  NGINX_RELOAD=0           (used for testing)
set -euo pipefail

OUT="${OUT:-/etc/nginx/conf.d/cloudflare-realip.conf}"
RELOAD="${NGINX_RELOAD:-1}"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

fetch() { curl -fsS --max-time 20 "https://www.cloudflare.com/$1"; }
V4="$(fetch ips-v4)"
V6="$(fetch ips-v6)"

{
  echo "# Generated by deploy/cloudflare-realip.sh on $(date -u +%Y-%m-%dT%H:%MZ) from https://www.cloudflare.com/ips"
  # only accept well-formed CIDR ranges so a bad download can never put garbage into the Nginx config
  while read -r cidr; do
    [[ "$cidr" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]] && echo "set_real_ip_from $cidr;"
  done <<< "$V4"
  while read -r cidr; do
    [[ "$cidr" =~ ^[0-9a-fA-F:]+/[0-9]{1,3}$ ]] && echo "set_real_ip_from $cidr;"
  done <<< "$V6"
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
} > "$TMP"

COUNT="$(grep -c '^set_real_ip_from' "$TMP" || true)"
[[ "$COUNT" -ge 10 ]] || { echo "refusing to install: only $COUNT Cloudflare ranges parsed" >&2; exit 1; }

install -m 0644 "$TMP" "$OUT"
echo "wrote $OUT ($COUNT ranges)"
if [[ "$RELOAD" == 1 ]]; then
  nginx -t && systemctl reload nginx
fi
